import numpy as np
import matplotlib.pyplot as plt

def generate_a_conjugate_directions(A, tol=1e-12):
    """
    Generate an A-conjugate set of directions using A-inner-product Gram-Schmidt.
    """
    A = np.asarray(A, dtype=float)
    n = A.shape[0]
    directions = []

    for k in range(n):
        p = np.zeros(n, dtype=float)
        p[k] = 1.0

        for q in directions:
            denom = q @ A @ q
            if abs(denom) < tol:
                continue
            p = p - ((q @ A @ p) / denom) * q

        norm_a = np.sqrt(max(p @ A @ p, 0.0))
        if norm_a < tol:
            continue

        directions.append(p / norm_a)

    return directions


def conjugate_direction_method(A, b, x0=None, tol=1e-10):
    """
    Solve Ax = b for SPD A using conjugate directions.
    """
    A = np.asarray(A, dtype=float)
    b = np.asarray(b, dtype=float)

    n = A.shape[0]
    if x0 is None:
        x = np.zeros(n, dtype=float)
    else:
        x = np.asarray(x0, dtype=float).copy()

    directions = generate_a_conjugate_directions(A, tol=tol)
    residuals = [np.linalg.norm(b - A @ x)]
    iterates = [x.copy()]

    for p in directions:
        r = b - A @ x
        denom = p @ A @ p
        if abs(denom) < tol:
            continue

        alpha = (r @ p) / denom
        x = x + alpha * p

        residuals.append(np.linalg.norm(b - A @ x))
        iterates.append(x.copy())

        if residuals[-1] < tol:
            break

    return x, np.array(residuals), np.array(iterates), directions


# Example
A = np.array([
    [4.0, 1.0, 0.0],
    [1.0, 3.0, 1.0],
    [0.0, 1.0, 2.0]
], dtype=float)

b = np.array([1.0, 2.0, 3.0], dtype=float)
x0 = np.zeros(3)

x_cd, res_cd, it_cd, dirs = conjugate_direction_method(A, b, x0=x0, tol=1e-12)

print("Conjugate Direction Solution x =", x_cd)
print("Residual norms =", res_cd)

for i in range(len(dirs)):
    for j in range(i):
        val = dirs[i] @ A @ dirs[j]
        print(f"p[{i}]^T A p[{j}] = {val:.3e}")